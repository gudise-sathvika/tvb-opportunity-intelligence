function tokenize(text: string): string[] {
  return text
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter((t) => t.length >= 3)
}

export async function handleIndiaGrantsBridge(
  request: IndiaGrantsBridgeSearchRequest | null,
): Promise<IndiaGrantsBridgeResult> {
  if (!request) {
    return {
      httpStatus: 400,
      body: {
        ok: false,
        status: 400,
        body: null,
        errors: [{ code: 'invalid_request', message: 'Missing Indian grants search request body.' }],
      },
    }
  }

  const query = (request.keyword ?? '').trim().toLowerCase()
  const queryTokens = tokenize(query)
  const limit = Math.max(1, Math.min(100, request.limit ?? 50))

  let filtered: IndiaGrantOpportunity[] = []
  if (queryTokens.length > 0) {
    const scored = INDIA_MASTER_GRANTS.map((grant) => {
      const haystack = `${grant.title} ${grant.description} ${grant.sectorFocus.join(' ')} ${grant.eligibleEntityTypes.join(' ')} ${grant.agency} ${grant.programName}`.toLowerCase()
      const matchCount = queryTokens.filter((token) => haystack.includes(token)).length
      return { grant, matchCount }
    })
    const directMatches = scored.filter((s) => s.matchCount > 0).sort((a, b) => b.matchCount - a.matchCount).map((s) => s.grant)
    const otherItems = scored.filter((s) => s.matchCount === 0).map((s) => s.grant)
    filtered = [...directMatches, ...otherItems]
  } else {
    filtered = [...INDIA_MASTER_GRANTS]
  }

  const results = filtered.slice(0, limit)

  return {
    httpStatus: 200,
    body: {
      ok: true,
      status: 200,
      body: JSON.stringify({
        ok: true,
        query,
        count: results.length,
        grants: results,
        source: 'Indian Innovation Grants (MeitY, iDEX, Startup India, DST)',
        queriedAt: request.requestedAt || new Date().toISOString(),
      }),
    },
  }
}
