function tokenize(text: string): string[] {
  return text
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter((t) => t.length >= 3)
}

export async function handleGemBridge(
  request: GemBridgeSearchRequest | null,
): Promise<GemBridgeResult> {
  if (!request) {
    return {
      httpStatus: 400,
      body: {
        ok: false,
        status: 400,
        body: null,
        errors: [{ code: 'invalid_request', message: 'Missing GeM search request body.' }],
      },
    }
  }

  const query = (request.keyword ?? '').trim().toLowerCase()
  const queryTokens = tokenize(query)
  const limit = Math.max(1, Math.min(100, request.limit ?? 50))

  let filtered: GemNotice[] = []
  if (queryTokens.length > 0) {
    const scored = GEM_MASTER_TENDERS.map((item) => {
      const haystack = `${item.title} ${item.description} ${item.categories.join(' ')} ${item.requirements.join(' ')} ${item.organization} ${item.ministry} ${item.state}`.toLowerCase()
      const matchCount = queryTokens.filter((token) => haystack.includes(token)).length
      return { item, matchCount }
    })
    const directMatches = scored.filter((s) => s.matchCount > 0).sort((a, b) => b.matchCount - a.matchCount).map((s) => s.item)
    const otherItems = scored.filter((s) => s.matchCount === 0).map((s) => s.item)
    filtered = [...directMatches, ...otherItems]
  } else {
    filtered = [...GEM_MASTER_TENDERS]
  }

  const results = filtered.slice(0, limit)

  return {
    httpStatus: 200,
    body: {
      ok: true,
      status: 200,
      body: JSON.stringify({
        ok: true,
        query,
        count: results.length,
        tenders: results,
        source: 'GeM & CPPP India',
        queriedAt: request.requestedAt || new Date().toISOString(),
      }),
    },
  }
}
